def _body(value):
    while isinstance(value, dict) and isinstance(value.get('result'), dict):
        value = value['result']
    return value


def _material_gaps(frame):
    from native_material_requirements import material_gaps
    return material_gaps(frame)


def verify_invoice_scope(form, manifest, frame):
    """A matching total alone cannot prove that the right invoices were saved."""
    selected=manifest.get('selected_invoices',[])
    if (not selected or manifest.get('case_id')!=form['case_id'] or manifest.get('serial')!=form['serial']
            or len(selected)!=form.get('expected_invoice_count') or len(selected)!=manifest.get('expected_count')
            or len({x.get('guid') for x in selected})!=len(selected) or any(not x.get('guid') for x in selected)):
        raise APIError('batch_invoice_binding','已选票据、单号、原生GUID或票数不完整，不能进入下一步')
    text=re.sub(r'\s+','',frame.get('visibleText',''))
    summaries=re.findall(r'共选择([0-9]+)张发票[,，、]?合计([0-9,.]+)元',text)
    face=sum((Decimal(x['amount']) for x in selected),Decimal('0'))
    if (len(summaries)!=1 or int(summaries[0][0])!=len(selected)
            or Decimal(summaries[0][1].replace(',',''))!=face or Decimal(manifest['expected_amount'])!=face):
        raise APIError('batch_invoice_readback','独立回读的票数或原票面合计不符，不能进入下一步')
    for invoice in selected:
        identity=invoice.get('number') if invoice.get('number_exposed',True) else invoice.get('native_code_abst')
        if not identity or re.sub(r'\s+','',str(identity)) not in text:
            raise APIError('batch_invoice_readback','独立回读未逐张覆盖已绑定票据身份，不能进入下一步')
    return {'invoice_count':len(selected),'invoice_face_amount':str(face)}


def _json_path(service, value):
    from reimbursement_standards import safe_path
    path = Path(value).resolve()
    root = next((r for r in service.material_roots if path.is_relative_to(r)), None)
    if not Path(value).is_absolute() or root is None or path.suffix != '.json':
        raise APIError('batch_path', '索引和计划须为授权材料根内的绝对JSON路径')
    path = safe_path(root, str(path.relative_to(root)))
    if path.stat().st_size > 16 * 1024 * 1024:
        raise APIError('batch_too_large', '批次JSON超过16MiB')
    return path


def _verified_file(service, value, expected_sha):
    path = _json_path(service, value) if Path(value).suffix == '.json' else service.material_path(str(value))
    if hashlib.sha256(path.read_bytes()).hexdigest() != expected_sha:
        raise APIError('batch_source_changed', '正式计划或输入SHA改变，须重新规划')
    return path


def _partial_payment_gaps(form, planned):
    """Allow only an explicitly empty corporate-payment section, never guessed bank data."""
    from validate_config import money, validate_basic_fields, validate_categories
    payments = planned.get('payments')
    if form.get('payments') != [] or not isinstance(payments, list) or not payments:
        return None
    if any(not isinstance(p, dict) or p.get('mode') != 'corporate_transfer'
           or not isinstance(p.get('name'), str) or not p['name'].strip() for p in payments):
        return None
    total = money(form.get('amount'))
    if total <= 0 or any(money(p.get('amount')) <= 0 for p in payments) or sum((money(p['amount']) for p in payments), Decimal('0')) != total:
        return None
    if form.get('system_mode', 'daily') != 'daily':
        raise ValueError('缺项办理只接已接通的日常报销模式')
    validate_basic_fields(form.get('basic', {}))
    validate_categories(form.get('expense_categories', []))
    if (form.get('budget_allocation_mode') != 'system_default_single_funding'
            or len(form.get('funding', [])) != 1 or form.get('expense_allocations')
            or form.get('funding_policy', {}).get('invoice_level_required')):
        raise ValueError('缺项办理须为已核单经费的系统自动预算，无未明手工分摊')
    funds = form['funding']
    if not re.fullmatch(r'[A-Za-z0-9]+', funds[0].get('code', '')) or money(funds[0].get('amount')) != total:
        raise ValueError('缺项办理经费代码或金额不闭合')
    return ['对公收款开户行、账户及原生支付方式尚未核实，收款栏保留空白；仅填写经费和基本信息']


def inspect_batch(service, scenario, batch_index, sequences=None, allow_incomplete=False):
    path = _json_path(service, str(batch_index))
    index = read_json(path)
    if index.get('schema') not in ['ustc-reviewed-equal-amount-plan-index-v1', 'ustc-reviewed-equal-amount-plan-index-v2', 'ustc-reviewed-batch-plan-index-v1']:
        raise APIError('batch_index_schema', '只接受工具产生的逐案正式计划索引')
    if not isinstance(scenario, str) or not re.fullmatch(r'[A-Za-z0-9_-]+', scenario):
        raise APIError('batch_scenario', 'scenario须为登记的专项profile_id')
    requested = None if sequences is None else set(sequences)
    if requested is not None and (not requested or any(type(x) is not int or x <= 0 for x in requested)):
        raise APIError('batch_sequences', '序号须为非空正整数列表')
    from workspace_config import standards_library
    current_profile = service.standards_read(str(standards_library(service.root)), scenario)
    rows, seen, cases = [], set(), set()
    for row in index.get('documents', []):
        seq = row.get('index')
        if type(seq) is not int or seq <= 0 or seq in seen:
            raise APIError('batch_duplicate_sequence', '索引序号缺失或重复')
        seen.add(seq)
        if requested is not None and seq not in requested:
            continue
        case_id = row.get('case_id') or row.get('proposed_case_id')
        if case_id in cases:
            raise APIError('batch_duplicate_case', '同一索引不能重复办理一个case_id')
        cases.add(case_id)
        plan_path = _verified_file(service, row['official_plan'], row['official_plan_sha256'])
        _verified_file(service, row['normalized_input'], row['normalized_input_sha256'])
        plan = read_json(plan_path)
        selection = plan.get('rule_selection', {})
        if selection.get('profile_id') != scenario or selection.get('case_id') != case_id or selection.get('status') != 'ready':
            raise APIError('batch_scenario_mismatch', '索引、已选专项与案件不一致')
        if selection.get('profile_sha256') != current_profile['sha256'] or selection.get('profile_revision') != current_profile['profile']['revision']:
            raise APIError('batch_rules_changed', '本批正式计划采用旧规则；先按当前专项重新规划')
        normalized = read_json(_json_path(service, row['normalized_input']))
        if normalized.get('schema') != 'ustc-reimbursement-batch-input-v1' or normalized.get('case_id') != case_id or plan.get('input_evidence', {}).get('sha256') != row['normalized_input_sha256']:
            raise APIError('batch_input_binding', '归一化输入案件或正式计划输入绑定不符')
        forms = [f for doc in plan.get('plan', {}).get('documents', []) for f in doc.get('forms', [])]
        if len(forms) != 1:
            raise APIError('batch_form_scope', '每个索引项须对应一个明确拆分后的报销单')
        planned = forms[0]
        if type(plan.get('effective_policy', {}).get('contact_in_summary')) is not bool:
            raise APIError('batch_contact_policy', '正式计划须明确当前联系人位于摘要或系统备注')
        normalized_documents = normalized.get('documents', [])
        if len(normalized_documents) != 1 or planned.get('summary_base') != normalized_documents[0].get('folder_name'):
            raise APIError('batch_folder_binding', '正式计划的摘要基名与原文件夹名称不符')
        if plan.get('effective_policy', {}).get('contact_in_summary') is False and planned.get('summary') != normalized_documents[0].get('folder_name'):
            raise APIError('batch_folder_binding', '当前规范摘要必须原样使用文件夹名，联系说明只能在备注')
        if planned.get('summary') != row.get('summary') or planned.get('remarks') != row.get('remarks') or planned.get('claim_amount') != row.get('claim_amount'):
            raise APIError('batch_plan_mismatch', '索引摘要、备注或金额与正式计划不符')
        blocked, recovery_required, source_pages = [], False, {}
        overview, form, partial_gaps = {}, {}, None
        try:
            overview = service.overview(case_id)
            _, paths = service.resolve(case_id)
            form, invoices = read_json(paths['form']), read_json(paths['invoices'])
            if overview.get('unverified_write') or overview.get('active_jobs'):
                recovery_required = True
                blocked.append('原任务未结束或有待回读写入，只恢复原任务')
            if allow_incomplete:
                partial_gaps = _partial_payment_gaps(form, planned)
            if not overview.get('input_validation', {}).get('ok') and not (
                    partial_gaps and overview.get('input_validation', {}).get('error') == 'payments合计与报销总额不符'):
                blocked.append(overview.get('input_validation', {}).get('error', '本案参数不完整'))
            if form.get('case_id') != case_id:
                blocked.append('本案参数的案件标识与正式计划不同')
            fields = form.get('basic', {}).get('fields', {})
            if fields.get('t-abst') != planned.get('summary') or fields.get('t-cl_abst', '') != (planned.get('remarks') or ''):
                blocked.append('本案摘要或系统备注与最新正式计划不符')
            if Decimal(str(form.get('amount', '0'))) != Decimal(row['claim_amount']):
                blocked.append('本案金额与正式计划不符')
            if not fields.get('t-is_have_changefee') or not fields.get('t-td_point'):
                blocked.append('项目负责人费用或退单地点尚未按原生枚举核对')
            if form.get('review', {}).get('workflow_started'):
                blocked.append('本案流程已启动，禁止批量重新填草稿')
            if not invoices.get('original_files'):
                blocked.append('尚未登记本案原件')
            planned_invoices = {i['invoice_id']:i for doc in plan['plan']['documents'] for i in doc['invoices']}
            target_numbers = [planned_invoices[i]['invoice_number'] for i in planned['invoice_ids']]
            for invoice_id in planned['invoice_ids']:
                invoice = planned_invoices[invoice_id]
                for source_ref in invoice.get('source_refs', []):
                    bound = re.fullmatch(r'(.+)#sha256=([a-fA-F0-9]{64})&page=([1-9]\d*)', source_ref)
                    if bound:
                        source_pages.setdefault(invoice['invoice_number'], set()).add(
                            (str(Path(bound.group(1)).resolve()), bound.group(2).lower(), int(bound.group(3))))
            actual_numbers = [n for original in invoices.get('original_files', []) for n in original.get('invoice_number_candidates', [])]
            if (len(target_numbers) != len(set(target_numbers)) or len(actual_numbers) != len(set(actual_numbers))
                    or set(actual_numbers) != set(target_numbers) or set(row.get('invoice_numbers', [])) != set(target_numbers)
                    or row.get('invoice_count') != len(target_numbers)):
                blocked.append('本案原件、索引及正式计划票号集合或票数不闭合')
            if sum((Decimal(planned_invoices[i]['face_amount']) for i in planned['invoice_ids']), Decimal('0')) != Decimal(form.get('amount', '0')):
                from finance_expense_amount import verify_case_reductions
                try:
                    expenses = [e for doc in plan['plan']['documents'] for e in doc['expenses'] if e['expense_id'] in planned['expense_ids']]
                    verify_case_reductions(service,case_id,form,invoices,expenses,planned_invoices,
                                           read_json(paths['case']).get('material_context',{}).get('native_reduction_receipts'))
                except (ValueError,KeyError,TypeError,OSError) as error:
                    blocked.append('票面总额与核定额不同，须先有真实原生减报能力及逐票映射：'+str(error))
            corporate = bool(form.get('payments')) and all(p.get('mode') == 'corporate_transfer' for p in form['payments'])
            if any(p.get('mode') not in ['bank_transfer', 'corporate_transfer'] for p in form.get('payments', [])) or (
                    any(p.get('mode') == 'corporate_transfer' for p in form.get('payments', [])) and not corporate):
                blocked.append('批量填审只接全个人转卡或全对公转账，不支持混合支付')
            if corporate:
                from validate_config import validate_corporate_payments
                validate_corporate_payments(form['payments'], form['amount'])
                allowed_sources = {source for sources in source_pages.values() for source in sources}
                for payment in form['payments']:
                    invoice_linked = False
                    for ref in payment['source_refs']:
                        bound = re.fullmatch(r'(.+)#sha256=([a-fA-F0-9]{64})&page=([1-9]\d*)', ref)
                        if not bound:
                            raise ValueError('对公收款信息来源须冻结材料路径、SHA及页码')
                        _verified_file(service, bound.group(1), bound.group(2).lower())
                        invoice_linked |= (str(Path(bound.group(1)).resolve()), bound.group(2).lower(), int(bound.group(3))) in allowed_sources
                    if not invoice_linked:
                        raise ValueError('对公收款信息须关联本案已核发票页及SHA')
            def totals(payments, id_field):
                values = {}
                for payment in payments:
                    key = (payment.get('mode'), payment.get('name')) if corporate else (payment.get('mode'), payment.get('name'), payment.get(id_field))
                    if not all(key):
                        raise ValueError('收款人身份来源不完整')
                    values[key] = values.get(key, Decimal('0')) + Decimal(payment['amount'])
                return values
            if not partial_gaps:
                try:
                    if totals(form.get('payments', []), 'person_id') != totals(planned.get('payments', []), 'student_id'):
                        blocked.append('本案收款姓名、学号或金额与已核计划不符')
                except ValueError as error:
                    blocked.append(str(error))
            context = normalized.get('case_context', {})
            expected_funding = context.get('funding', {}).get('code')
            expected_witness = context.get('witness', {})
            if not expected_funding or {f.get('code') for f in form.get('funding', [])} != {expected_funding}:
                blocked.append('本案经费与本案已核输入不符')
            if (form.get('basic', {}).get('teacher_id') != expected_witness.get('person_id')
                    or form.get('basic', {}).get('teacher_name') != expected_witness.get('name')):
                blocked.append('本案证明人与本案已核输入不符')
            for original in invoices.get('original_files', []):
                _verified_file(service, original['path'], original['sha256'])
                for number in original.get('invoice_number_candidates', []):
                    matches = [i for i in planned_invoices.values() if i.get('invoice_number') == number]
                    allowed = set()
                    for invoice in matches:
                        for source_ref in invoice.get('source_refs', []):
                            bound = re.fullmatch(r'(.+)#sha256=([a-fA-F0-9]{64})&page=([1-9]\d*)', source_ref)
                            if bound:
                                allowed.add((str(Path(bound.group(1)).resolve()), bound.group(2).lower()))
                    if (str(Path(original['path']).resolve()), original['sha256'].lower()) not in allowed:
                        blocked.append('原件路径/SHA不属于本票已核定的页级来源')
                if original.get('ocr_issues') and original.get('visual_check') != 'verified':
                    blocked.append('原件识别差项须先核对并登记')
        except (APIError, ValueError, KeyError) as error:
            blocked.append(str(error))
        rows.append({'sequence': seq, 'case_id': case_id, 'summary': row.get('summary'),
                     'amount': row.get('claim_amount'), 'serial': form.get('serial'),
                     'ready_for_draft': not blocked, 'needed_inputs': blocked,
                     'fill_scope': 'basic_funding_only' if partial_gaps else 'complete_draft',
                     'deferred_inputs': partial_gaps or [],
                     'recovery_required': recovery_required,
                     'operator_verified_stages': overview.get('operator_verified_stages', []),
                     'known_state': overview.get('known_state'), 'state_is_cached_not_live':True,
                     'final_approver_pending': str(row.get('finance_readiness', '')).startswith('blocked'),
                     '_revision': overview.get('revision'),
                     '_source_pages': source_pages,
                     '_partial': bool(partial_gaps),
                     '_row': row})
    if requested is not None and requested - seen:
        raise APIError('batch_sequence_missing', '指定序号不在本批正式索引中')
    return path, rows


class DraftBatch:
    def __init__(self, service, index, scenario, tab, userid):
        self.service, self.tab, self.userid = service, tab, userid
        self.index, self.scenario = index, scenario
        self.key = hashlib.sha256(index.read_bytes() + scenario.encode()).hexdigest()[:12]
        self.folder = service.root / '.local/batch_workflows' / self.key
        self.folder.mkdir(parents=True, exist_ok=True)

    def request(self, case, label, method='enqueue', parameters=None, execute=False, **kwargs):
        rid = 'batch-' + self.key + '-' + label
        if method == 'enqueue':
            result = self.service.enqueue(case, kwargs.pop('operation'), parameters or {}, rid, execute)
        else:
            if method == 'invoice_selection':
                kwargs['execute'] = execute
            result = getattr(self.service, method)(case_id=case, request_id=rid, **kwargs)
        # A reused terminal enqueue is an identity/status stub, not the saved
        # result. Read the original registered artifacts; never dispatch again.
        if result.get('reused_existing_job') is True and result.get('status') not in ['queued', 'running']:
            result = self.service.result(case, result['job_id'])
        deadline = time.monotonic() + 300
        while result.get('status') in ['queued', 'running'] and time.monotonic() < deadline:
            time.sleep(.5)
            result = self.service.result(case, result['job_id'])
        atomic_json(self.folder / case / (label + '.json'), result)
        if not result.get('ok'):
            raise APIError('batch_step_stopped', '原任务需核对：' + str(result.get('job_id')) + '；' + str(result.get('error')))
        return result

    def artifact(self, case, result, name='output.json', *, envelope=False):
        matches = [a for a in result.get('artifacts', []) if a['name'] == name]
        if len(matches) != 1:
            raise APIError('batch_artifact', '正式任务缺少唯一指定回执：' + name)
        art = matches[0]
        path = self.service.artifact(case, result['job_id'], art['artifact_id'])
        value = read_json(path)
        return (value if envelope else _body(value)), art

    def readback(self, case, label):
        _, paths = self.service.resolve(case)
        form = read_json(paths['form'])
        for attempt in range(4):
            result = self.request(case, label + '-rb-' + str(time.time_ns()), operation='read_system', parameters={'mode':'readback','tab_id':self.tab})
            data, art = self.artifact(case, result)
            frames = [f for f in data.get('frames', []) if f.get('id') == 'iframepage_print' and '报销单号：' + form['serial'] in f.get('visibleText', '')]
            if data.get('serial') != form['serial'] or data.get('identity', {}).get('userid') != self.userid or data.get('visibleDialogs'):
                raise APIError('batch_readback', '回读身份、同号预览或窗口状态未确认；保留原写入，禁止自动重放')
            if len(frames) == 1:
                inventory = frames[0].get('proof_inventory', {})
                if inventory.get('document_ready_state') in ['loading', 'interactive']:
                    if attempt == 3:
                        raise APIError('batch_readback_loading', '同号原生预览仍在加载；保留原写入，只重新回读')
                    time.sleep(.5)
                    continue
                break
            empty_preview = [f for f in data.get('frames', []) if f.get('id') == 'iframepage_print' and not f.get('visibleText', '').strip()]
            if len(empty_preview) != 1 or attempt == 3:
                raise APIError('batch_readback', '同号预览尚未就绪；保留原写入，只恢复原任务')
            time.sleep(.5)  # Only another read of the same native page, never another save.
        total = re.search(r'金额总计[：:]\s*([\d,]+\.\d{2})', frames[0]['visibleText'])
        if total is None or Decimal(total.group(1).replace(',', '')) != Decimal(form['amount']):
            raise APIError('batch_readback_amount', '同号预览总金额与本案不符，禁止登记保存')
        verify_invoice_scope(form,read_json(paths['invoices']),frames[0])
        return result, data, frames[0], art

    def ack(self, case, readback, art, note):
        return self.request(case, 'ack-' + readback['job_id'], operation='record_result',
                            parameters={'kind':'ack-write','job_id':readback['job_id'],'artifact_id':art['artifact_id'],
                                        'outcome':'saved','note':note})

    def verify_stage(self, case, stage, frame):
        _, paths = self.service.resolve(case)
        form = read_json(paths['form']); text = frame['visibleText']
        if stage == 'basic':
            from finance_basic_verify import verify_basic_fields
            verify_basic_fields(form, frame)
        elif stage == 'categories':
            from finance_category_verify import verify_categories
            verify_categories(form, frame)
        elif stage in ['funding', 'expenses']:
            codes = set(re.findall(r'([A-Z]{2}\d{10})/', text))
            expected = {f['code'] for f in form['funding']}
            budget_rows = [row for table in frame.get('tables', []) for row in table
                           if len(row) == 5 and re.search(r'[A-Z]{2}\d{10}/', row[2])]
            allocated = sum((Decimal(row[4].replace(',', '')) for row in budget_rows), Decimal('0'))
            if len(form['funding']) != 1 or codes != expected or allocated != Decimal(form['amount']):
                raise APIError('batch_funding_readback', '经费或金额与本案不符')
        elif stage == 'payments':
            if form.get('payments') and all(p.get('mode') == 'corporate_transfer' for p in form['payments']):
                from finance_corporate_verify import verify_corporate_fields
                verify_corporate_fields(form, frame)
                return form
            rows = [row for table in frame.get('tables', []) for row in table]
            actual = [row for row in rows if len(row) == 7 and row[-1] == '转卡信息完整']
            if len(actual) != len(form['payments']) or sum((Decimal(row[5].replace(',', '')) for row in actual), Decimal('0')) != Decimal(form['amount']):
                raise APIError('batch_payments_readback', '转卡条数或总金额不闭合')
            for pay in form['payments']:
                if pay['mode'] != 'bank_transfer' or not any(pay['person_id'] in row and pay['name'] in row and format(Decimal(pay['amount']), ',.2f') in row and '转卡信息完整' in row for row in rows):
                    raise APIError('batch_payments_readback', '收款身份、银行卡联动及金额未独立核实')
        elif stage == 'payments_empty':
            rows = [row for table in frame.get('tables', []) for row in table]
            if (form.get('payments') != [] or rows.count(['支付方式', '请填写支付方式']) != 1
                    or '请填写支付信息' not in text or any(len(row) == 7 and row[-1] == '转卡信息完整' for row in rows)):
                raise APIError('batch_partial_payment_readback', '缺项办理须独立确认系统收款栏仍空白；发现原生已有支付信息，不替用户删除或改写')
        else:
            raise APIError('batch_unknown_verification_stage','未知步骤不能默认视为已核对：'+str(stage))
        return form

    def fill_stage(self, case, stage):
        self.request(case, stage + '-plan', operation='stage', parameters={'stage':stage,'tab_id':self.tab})
        self.request(case, stage + '-write', operation='stage', parameters={'stage':stage,'tab_id':self.tab}, execute=True)
        receipt, data, frame, art = self.readback(case, stage)
        form = self.verify_stage(case, stage, frame)
        self.ack(case, receipt, art, '参数式批量办理独立回读：' + stage + '同号' + form['serial'] + '身份、目标字段及金额与本案参数一致；未执行本人同意、审批或付款。')

    def create(self, case, row, source_pages):
        from finance_upload_batch_run import run_batch, partition_sources, recover_budget_rejection
        from invoice_identity import source_matches
        _, initial_paths = self.service.resolve(case)
        initial_manifest = read_json(initial_paths['invoices'])
        if initial_manifest.get('serial') or initial_manifest.get('draft_creation_requested'):
            raise APIError('batch_create_original_pending', '已有原建单请求或单号；只恢复原结果，不重新导航选票')
        numbers = row['invoice_numbers']
        if not 1 <= len(numbers) <= 20:
            raise APIError('batch_selection_scope', '当前每个已拆索引项须1至20张票，更多票保留待分批选票')
        source = self.request(case, 'sources', method='invoice_sources', action='manifest', invoice_numbers=numbers)
        manifest, source_art = self.artifact(case, source)
        _, paths = self.service.resolve(case)
        originals = read_json(paths['invoices'])['original_files']
        source_files = manifest.get('original_files', [])
        if (manifest.get('expected_count') != len(source_files)
                or {(r['path'], r['sha256']) for r in originals} != {(r['path'], r['sha256']) for r in source_files}):
            raise APIError('batch_manifest_scope', '正式来源与本案冻结原件路径/SHA/文件数不闭合')
        source_numbers = []
        for original in source_files:
            for record in original.get('invoice_records', []):
                number = record.get('number'); source_numbers.append(number)
                binding = (str(Path(original['path']).resolve()), original['sha256'].lower(), record.get('page'))
                if binding not in source_pages.get(number, set()):
                    raise APIError('batch_manifest_page', '来源票号/原件SHA/页码不属于本单已核计划')
        if len(source_numbers) != len(numbers) or set(source_numbers) != set(numbers):
            raise APIError('batch_manifest_scope', '正式来源票号全集与本单不同，禁止混传或漏票')
        audits = []
        for offset in range(0, len(numbers), 20):
            audit = self.request(case, 'audit-' + str(offset), method='invoice_sources', action='audit', invoice_numbers=numbers[offset:offset+20])
            _, art = self.artifact(case, audit)
            audits.append({'job_id':audit['job_id'],'artifact_id':art['artifact_id']})
        # Navigation and visible query state are current browser facts. Reusing
        # a completed navigation or a failed read from an earlier invocation
        # cannot establish this invocation's pool. Writes retain stable IDs.
        current_pool = str(time.time_ns())
        self.request(case, 'open-pool-' + current_pool, operation='invoice', parameters={'action':'open-pool','tab_id':self.tab}, execute=True)
        pool = self.request(case, 'pool-before-' + current_pool, method='invoice_verification', action='full-grid', grid='53', tab_id=self.tab, expected_userid=self.userid)
        native, _ = self.artifact(case, pool)
        rows = native['grids'][0]['rows']
        missing = []
        for original in manifest['original_files']:
            hits = [r for r in rows if source_matches(r, original)]
            if len(hits) > 1 or any(r.get('t.auth_rst_desc') != '正常(已认证)' or str(r.get('t.serial_no', '')).strip() for r in hits):
                raise APIError('batch_pool_conflict', '本案票据重复、非正常认证或已被占用，禁止重传建单')
            if not hits:
                missing.append(original)
        batches = partition_sources(missing)
        missing_sha = {s['sha256'] for s in missing}
        for prior_manifest in (self.folder/case).glob('upload*.manifest.json'):
            prior_folder = prior_manifest.with_name(prior_manifest.name.removesuffix('.manifest.json'))
            if prior_folder.exists() and missing_sha & {s['sha256'] for s in read_json(prior_manifest)['original_files']}:
                recover_budget_rejection(prior_manifest, self.tab, prior_folder)
        for chunk in batches:
            identity = hashlib.sha256(json.dumps([(s['path'],s['sha256']) for s in chunk],ensure_ascii=False).encode()).hexdigest()[:16]
            folder = self.folder / case / ('upload-sized-' + identity)
            mpath = self.folder / case / ('upload-sized-' + identity + '.manifest.json')
            if folder.exists():
                raise APIError('batch_upload_unknown', '原上传任务目录已存在；只恢复原回执，不自动重传')
            atomic_json(mpath, {**manifest, 'original_files':chunk, 'expected_count':len(chunk), 'expected_userid':self.userid})
            summary = run_batch(mpath, self.tab, folder)
            if not summary.get('verification_complete') or any(x['status'] != 'authenticated' for x in summary['classified']):
                raise APIError('batch_upload_status', '本批识别尚未正常认证；保留原任务')
        preview = self.request(case, 'select-plan', method='invoice_selection', action='preview', tab_id=self.tab,
                               source_job_id=source['job_id'], source_artifact_id=source_art['artifact_id'], audit_refs=audits,
                               selectors=[{'invoice_number':number} for number in numbers], mode='replace', grid='53', expected_userid=self.userid)
        plan, part = self.artifact(case, preview)
        if not plan.get('apply_ready') or Decimal(plan['candidate_amount']) != Decimal(row['claim_amount']):
            raise APIError('batch_selection_plan', '选票未就绪或选中票面合计不等于核定金额')
        self.request(case, 'select-apply', method='invoice_selection', action='apply', tab_id=self.tab,
                     preview_job_id=preview['job_id'], preview_artifact_id=part['artifact_id'], execute=True)
        read = self.request(case, 'select-read', method='invoice_selection', action='readback', tab_id=self.tab,
                            preview_job_id=preview['job_id'], preview_artifact_id=part['artifact_id'])
        _, art = self.artifact(case, read, 'output-snapshot.json')
        self.request(case, 'select-register', operation='record_result', parameters={'kind':'select-invoices','job_id':read['job_id'],'artifact_id':art['artifact_id']})
        self.request(case, 'create', operation='invoice', parameters={'action':'create-draft','tab_id':self.tab}, execute=True)
        # Creation can return before the native asynchronous preview. Only new reads follow.
        for attempt in range(6):
            read = self.request(case, 'creation-read-' + str(attempt), operation='read_system', parameters={'mode':'readback','tab_id':self.tab})
            data, art = self.artifact(case, read, 'invoice.json')
            serial = str(data.get('serial', '')).strip()
            frames = [f for f in data.get('frames', []) if f.get('id') == 'iframepage_print' and '报销单号：' + serial in f.get('visibleText', '')]
            if re.fullmatch(r'\d+', serial) and len(frames) == 1:
                text = re.sub(r'\s+', '', frames[0]['visibleText']).replace(',', '')
                expected = '共选择' + str(len(numbers)) + '张发票合计' + format(Decimal(row['claim_amount']), '.2f') + '元'
                if (data.get('identity', {}).get('userid') != self.userid or data.get('projid') != 'WF_YBX'
                        or data.get('visibleDialogs') or expected not in text or any(number not in text for number in numbers)):
                    raise APIError('batch_creation_binding', '原建单同号回读的身份、系统、票号全集、票数或金额不符；禁止绑定和后续填报')
                self.request(case, 'bind', operation='record_result', parameters={'kind':'bind-serial','job_id':read['job_id'],'artifact_id':art['artifact_id'],'serial':serial})
                self.readback(case, 'created-draft-current')
                return
            time.sleep(2)
        raise APIError('batch_create_unknown', '原建单请求尚无完整同号预览；保留pending，只恢复原任务')

    def verify_existing(self, item):
        """Derive a new completion from the typed open route's one fresh preview.

        This does not acknowledge a write or edit the case's operator state.
        The prior completion remains recoverable as its exact original bytes.
        """
        from finance_open_draft import verify_preview
        from batch_delivery import _frame
        from submission import verify_options
        from operator_support import stamp

        case, row = item['case_id'], item['_row']
        _, paths = self.service.resolve(case)
        state = self.folder / case / 'completed.json'
        prior = state.read_bytes() if state.exists() else None
        frozen = {key: hashlib.sha256(paths[key].read_bytes()).hexdigest()
                  for key in ['case', 'form', 'invoices', 'state']}
        index_sha = hashlib.sha256(self.index.read_bytes()).hexdigest()
        form = read_json(paths['form'])
        overview = self.service.overview(case)
        if (overview.get('revision') != item['_revision'] or overview.get('unverified_write')
                or overview.get('active_jobs') or (paths['state'].parent/'pending_write.json').exists()):
            raise APIError('batch_verify_pending', '核验前本案版本已变或仍有原任务；保留原完成记录')
        if not form.get('serial') or item.get('_partial'):
            raise APIError('batch_verify_existing', '只读核验须已有明确单号及完整付款参数')
        explanations = form.get('explanations') or {}
        if (explanations.get('record_only') is not True
                and (explanations.get('general') or any(x.get('text') for x in explanations.get('card_notes', [])))):
            raise APIError('batch_verify_explanations', '本案有须核对的已保存说明；只读预览未含该证据，保留原完成记录')

        receipt = self.request(case, 'verify-existing-' + str(time.time_ns()), operation='read_system',
                               parameters={'mode':'open-draft', 'serial':form['serial'],
                                           'expected_userid':self.userid, 'tab_id':self.tab})
        if receipt.get('status') != 'completed' or receipt.get('exit_code') != 0:
            raise APIError('batch_verify_job', '打开原单的正式只读任务未完整结束，保留原完成记录')
        envelope, art = self.artifact(case, receipt, envelope=True)
        native_path = self.service.artifact(case, receipt['job_id'], art['artifact_id'])
        if hashlib.sha256(native_path.read_bytes()).hexdigest() != art.get('sha256'):
            raise APIError('batch_verify_artifact', '正式只读预览的注册SHA不符，保留原完成记录')
        data = verify_preview(envelope, form['serial'], self.userid, self.tab)
        planned = [f for doc in read_json(Path(row['official_plan']))['plan']['documents']
                   for f in doc['forms']]
        if len(planned) != 1:
            raise APIError('batch_verify_plan', '本次原单须对应唯一已核正式计划')
        frame = _frame(data, form, {**row, 'planned':planned[0]}, self.userid)
        for stage in ['basic', 'funding', 'payments']:
            self.verify_stage(case, stage, frame)
        if form.get('expense_categories'):
            self.verify_stage(case, 'categories', frame)
        try:
            verify_options(data, form['serial'])
        except ValueError as error:
            raise APIError('batch_verify_options', str(error)) from error
        for person in form.get('pre_review', []):
            if person['id'] + '(' + person['name'] + ')' not in frame['visibleText']:
                raise APIError('batch_verify_pre_review', '本案预审人未逐项独立回读，保留原完成记录')
        gaps = _material_gaps(frame)
        from finance_category_verify import review_material_prompt
        category_review = review_material_prompt(form, frame, gaps)
        result = {'sequence':item['sequence'], 'case_id':case, 'serial':form['serial'], 'amount':form['amount'],
                  'status':'draft_filled_system_material_gaps' if gaps else 'draft_filled_native_audit_passed',
                  'verification_method':'read_only_existing_draft', 'verified_at_utc':stamp(),
                  'verified_field_groups':['basic','funding','payments'], 'options_verified':True,
                  'system_evidence_gaps':gaps, 'ready_for_material_delivery':False,
                  'category_review':category_review,
                  'system_write':False, 'local_record_updated':True, 'pdf_exported':False,
                  'workflow_started':False, 'approval_completed':False, 'payment_completed':False,
                  'form_sha256':frozen['form'],
                  'native_evidence':{'job_id':receipt['job_id'], 'artifact_id':art['artifact_id'], 'sha256':art['sha256']}}
        # Use the existing case lease only after the read worker has released it.
        with self.service.mutex(case):
            _, current = inspect_batch(self.service, self.scenario, self.index, [item['sequence']])
            if (len(current) != 1 or not current[0]['ready_for_draft']
                    or current[0]['_revision'] != item['_revision']
                    or hashlib.sha256(self.index.read_bytes()).hexdigest() != index_sha
                    or any(hashlib.sha256(paths[key].read_bytes()).hexdigest() != value for key, value in frozen.items())
                    or (paths['state'].parent/'pending_write.json').exists()
                    or self.service.overview(case).get('unverified_write')
                    or self.service.overview(case).get('active_jobs')
                    or (state.read_bytes() if state.exists() else None) != prior):
                raise APIError('batch_verify_changed', '核验期间案件、来源、原任务或旧完成记录改变；不覆盖旧记录')
            state.parent.mkdir(parents=True, exist_ok=True)
            if prior is not None:
                prior_sha = hashlib.sha256(prior).hexdigest()
                history = state.parent/'completion-history'/('completed-' + prior_sha + '-' + str(time.time_ns()) + '.json')
                history.parent.mkdir(parents=True, exist_ok=True)
                with history.open('xb') as stream:
                    stream.write(prior)
                result['prior_completion'] = {'path':str(history), 'sha256':prior_sha}
            atomic_json(state, result)
        return result

    def run_case(self, item):
        case, row = item['case_id'], item['_row']
        partial = item.get('_partial', False)
        state = self.folder / case / ('partial.json' if partial else 'completed.json')
        if state.exists():
            cached = read_json(state)
            _, paths = self.service.resolve(case)
            evidence = cached.get('native_evidence', {})
            if cached.get('form_sha256') != hashlib.sha256(paths['form'].read_bytes()).hexdigest() or not evidence:
                raise APIError('batch_completion_evidence', '旧完成标记缺证据或参数已改变，须核对原任务')
            native_path = self.service.artifact(case, evidence.get('job_id'), evidence.get('artifact_id'))
            if hashlib.sha256(native_path.read_bytes()).hexdigest() != evidence.get('sha256'):
                raise APIError('batch_completion_evidence', '完成标记的独立原生回执SHA不符')
            overview = self.service.overview(case)
            if overview.get('unverified_write') or overview.get('active_jobs'):
                raise APIError('batch_completion_pending', '完成标记后仍有未核任务，先恢复原任务')
            if not partial:
                native = _body(read_json(native_path))
                frames = [f for f in native.get('frames', []) if f.get('id') == 'iframepage_print'
                          and '报销单号：' + cached['serial'] in f.get('visibleText', '')]
                if len(frames) != 1 or native.get('serial') != cached['serial']:
                    raise APIError('batch_completion_evidence', '完成标记的原生同号预览缺失')
                gaps = _material_gaps(frames[0])
                from finance_category_verify import review_material_prompt, verify_categories
                current_form = read_json(paths['form'])
                if current_form.get('expense_categories'):
                    verify_categories(current_form, frames[0])
                cached = {**cached, 'system_evidence_gaps':gaps,
                          'category_review':review_material_prompt(current_form, frames[0], gaps),
                          'status':'draft_filled_system_material_gaps' if gaps else 'draft_filled_native_audit_passed'}
            return {**cached, 'state_is_cached_not_live':True}
        _, paths = self.service.resolve(case)
        if self.service.overview(case).get('revision') != item['_revision']:
            raise APIError('batch_input_changed', '本案参数在预检后改变，须重新预检原任务')
        form = read_json(paths['form'])
        if not form.get('serial'):
            self.create(case, row, item['_source_pages'])
        else:
            # resume-draft is specifically for a rejected creation, never an existing serial.
            # Existing drafts may continue only when already open and independently verified.
            self.readback(case, 'existing-draft-current')
        # Explicitly empty remittance remarks; never inherit the summary from the native default.
        form = read_json(paths['form']); overview = self.service.overview(case)
        if not partial:
            payments = [{**p, 'remark':p.get('remark', '')} for p in form['payments']]
            changed = self.service.update_case(case, 'form', {'payments':payments}, overview['revision'])
            if not changed.get('ok'):
                raise APIError('batch_revision', '填写前参数版本改变，停止本案')
        verified = set(self.service.overview(case).get('operator_verified_stages', []))
        if partial:
            _, _, frame, _ = self.readback(case, 'partial-payment-empty-before')
            self.verify_stage(case, 'payments_empty', frame)
        stages = ['funding', 'basic'] if partial else ['funding', 'basic', 'expenses', 'payments']
        if not partial and form.get('expense_categories'):
            stages.insert(stages.index('expenses'), 'categories')
        for stage in stages:
            if stage in verified:
                _, _, frame, _ = self.readback(case, stage + '-previously-verified')
                self.verify_stage(case, stage, frame)
            else:
                self.fill_stage(case, stage)
        form = read_json(paths['form'])
        if partial:
            if form.get('payments') != []:
                raise APIError('batch_partial_changed', '缺项办理期间收款参数改变，须重新核对原任务')
            receipt, _, frame, art = self.readback(case, 'partial-final')
            for stage in ['basic', 'funding', 'payments_empty']:
                self.verify_stage(case, stage, frame)
            result = {'sequence':item['sequence'],'case_id':case,'serial':form['serial'],'amount':form['amount'],
                      'status':'draft_partially_filled_missing_payment','verified_stages':['funding','basic'],
                      'deferred_inputs':item.get('deferred_inputs', []),
                      'pdf_exported':False,'workflow_started':False,'approval_completed':False,'payment_completed':False,
                      'ready_for_material_delivery':False,
                      'form_sha256':hashlib.sha256(paths['form'].read_bytes()).hexdigest(),
                      'native_evidence':{'job_id':receipt['job_id'],'artifact_id':art['artifact_id'],'sha256':art['sha256']}}
            atomic_json(state, result)
            return result
        plan = {'case_id':case,'serial':form['serial'],'amount':form['amount'],'summary':form['basic']['fields']['t-abst'],
                'phone':form['basic']['fields']['t-req_mobile'],'submit_authorized':True,
                'source':'用户明确授权本批参数式做单；仅无合同/不委托打印选项，不推进审批或本人同意',
                'contract_exists':False,'delegate_finance_print':False}
        from submission import verify_options
        _, before_options, _, _ = self.readback(case, 'options-current')
        try:
            verify_options(before_options, form['serial'])
            options_ready = True
        except ValueError:
            options_ready = False
        if not options_ready:
            self.request(case, 'options-native-applicability-v3', operation='submission', parameters={'action':'options','plan':plan,'tab_id':self.tab}, execute=True)
            receipt, data, _, art = self.readback(case, 'options')
            verify_options(data, form['serial'])
            self.ack(case, receipt, art, '独立回读同号：合同无、委托财务打印否；未推进流程。')
        if 'audit' not in verified:
            self.request(case, 'final-audit', operation='stage', parameters={'stage':'audit','tab_id':self.tab}, execute=True)
        receipt, data, frame, art = self.readback(case, 'final-audit')
        for stage in ['basic', 'funding', 'payments']:
            self.verify_stage(case, stage, frame)
        if form.get('expense_categories'):
            self.verify_stage(case, 'categories', frame)
        verify_options(data, form['serial'])
        if 'audit' not in verified:
            self.ack(case, receipt, art, '原生audit后独立同号预览身份、金额和已核参数一致；仅草稿填审通过，未执行本人同意、审批或付款。')
        result = {'sequence':item['sequence'],'case_id':case,'serial':form['serial'],'amount':form['amount'],
                  'status':'draft_filled_native_audit_passed','pdf_exported':False,'workflow_started':False,
                  'approval_completed':False,'payment_completed':False,
                  'form_sha256':hashlib.sha256(paths['form'].read_bytes()).hexdigest(),
                  'native_evidence':{'job_id':receipt['job_id'],'artifact_id':art['artifact_id'],'sha256':art['sha256']}}
        result['system_evidence_gaps'] = _material_gaps(frame)
        from finance_category_verify import review_material_prompt
        result['category_review'] = review_material_prompt(form, frame, result['system_evidence_gaps'])
        if result['system_evidence_gaps']:
            result['status'] = 'draft_filled_system_material_gaps'
        result['ready_for_material_delivery'] = False
        atomic_json(state, result)
        return result


def run_batch(service, *, scenario, batch_index, phase='status', sequences=None,
              tab_id=None, expected_userid=None, execute=False, allow_incomplete=False):
    if phase not in ['status', 'run', 'recover', 'verify']:
        raise APIError('batch_phase', 'phase只支持status/run/recover/verify')
    if execute and phase not in ['run', 'recover', 'verify']:
        raise APIError('batch_execute', '只有run/recover/verify阶段接受execute')
    if type(allow_incomplete) is not bool:
        raise APIError('batch_allow_incomplete', 'allow_incomplete须为显式布尔参数')
    path, items = inspect_batch(service, scenario, batch_index, sequences, allow_incomplete)
    if phase == 'verify':
        for item in items:
            if not item.get('serial') or item.get('_partial'):
                item['ready_for_draft'] = False
                item['needed_inputs'].append('只读核验须已有明确单号及完整付款参数')
    public = [{k:v for k,v in x.items() if not k.startswith('_')} for x in items]
    result = {'ok':True,'scenario':scenario,'batch_index':str(path),'phase':phase,'execute':execute,
              'allow_incomplete':allow_incomplete,
              'documents':public,'ready_count':sum(x['ready_for_draft'] for x in items),
              'system_write':False,'approval_completed':False,'payment_completed':False,'pdf_exported':0}
    if phase == 'status' or not execute:
        return result
    if not isinstance(tab_id, str) or not re.fullmatch(r'\d+', tab_id) or not expected_userid:
        raise APIError('batch_identity', '实际执行须当前tab_id及本案expected_userid')
    if phase == 'verify':
        if any(not item['ready_for_draft'] or item['recovery_required'] for item in items):
            return {**result, 'ok':False, 'state':'verify_existing_blocked', 'results':[], 'local_record_updated':False}
        runner = DraftBatch(service, path, scenario, tab_id, expected_userid)
        results = []
        for item in items:
            try:
                results.append(runner.verify_existing(item))
            except (ValueError, OSError, KeyError, RuntimeError, subprocess.SubprocessError) as error:
                results.append({'sequence':item['sequence'], 'case_id':item['case_id'],
                                'status':'stopped_verify_original', 'error':str(error)})
                result['ok'] = False
                break
        return {**result, 'state':'existing_drafts_verified' if result['ok'] else 'stopped_verify_original',
                'results':results, 'receipt_root':str(runner.folder),
                'verified_count':sum(x.get('local_record_updated') is True for x in results),
                'local_record_updated':any(x.get('local_record_updated') is True for x in results)}
    if phase == 'recover':
        targets = [item for item in items if item['recovery_required']]
        if len(targets) != 1:
            raise APIError('batch_recovery_scope', '恢复须用sequences明确一个有原pending的当前单据')
        item = targets[0]; case = item['case_id']
        overview = service.overview(case)
        if overview.get('active_jobs'):
            raise APIError('batch_recovery_running', '原任务仍在执行，先查原result，不并发恢复')
        pending = overview.get('unverified_write') or {}
        operation = pending.get('operation', '')
        stage = operation.removeprefix('step:') if operation.startswith('step:') else 'options' if operation == 'submission:options' else None
        if stage not in ['basic', 'funding', 'expenses', 'payments', 'audit', 'options']:
            raise APIError('batch_recovery_action', '此原写入须使用其专用恢复入口，批次不重放或猜测结果')
        runner = DraftBatch(service, path, scenario, tab_id, expected_userid)
        receipt, data, frame, art = runner.readback(case, 'recover-' + stage)
        if stage in ['audit', 'options']:
            for part in ['basic', 'funding', 'payments']:
                runner.verify_stage(case, part, frame)
            from submission import verify_options
            verify_options(data, item['serial'])
        else:
            runner.verify_stage(case, stage, frame)
        runner.ack(case, receipt, art, '恢复原' + operation + '：独立同号原生预览核对目标字段及金额已持久保存；未重放原保存，未推进审批。')
        return {**result, 'local_record_updated':True,'state':'original_saved_independently_verified',
                'results':[{'case_id':case,'serial':item['serial'],'recovered_stage':stage,
                            'readback_job_id':receipt['job_id'],'replayed':False}], 'receipt_root':str(runner.folder)}
    if any(item['recovery_required'] for item in items):
        return {**result, 'ok':False,'state':'recover_original_before_batch','results':[],
                'needed_inputs':['所选案有原任务未结束或待回读写入；共享现场须先恢复原任务，不开始其他案']}
    runner = DraftBatch(service, path, scenario, tab_id, expected_userid)
    results = []
    for item in items:
        if not item['ready_for_draft']:
            results.append({**{k:v for k,v in item.items() if not k.startswith('_')},'status':'held_missing_inputs'})
            continue
        try:
            results.append(runner.run_case(item))
        except (ValueError, OSError, KeyError, RuntimeError, subprocess.SubprocessError) as error:
            results.append({'sequence':item['sequence'],'case_id':item['case_id'],'status':'stopped_verify_original','error':str(error)})
            result['ok'] = False
            break  # A shared live page may retain an unknown write: never move to another case.
        finally:
            atomic_json(runner.folder/'progress.json', {'scenario':scenario,'results':results,'approval_completed':False,'payment_completed':False})
    result.update(system_write=True, results=results, receipt_root=str(runner.folder),
                  filled_count=sum(x.get('status') in ['draft_filled_native_audit_passed','draft_filled_system_material_gaps'] for x in results),
                  audit_passed_count=sum(x.get('status')=='draft_filled_native_audit_passed' for x in results),
                  material_gap_count=sum(x.get('status')=='draft_filled_system_material_gaps' for x in results),
                  partially_filled_count=sum(x.get('status')=='draft_partially_filled_missing_payment' for x in results))
    return result
